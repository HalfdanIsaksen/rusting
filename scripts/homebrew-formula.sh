#!/usr/bin/env bash
# Writes Formula/rusting.rb for a released version.
#
# Usage: scripts/homebrew-formula.sh <version> <sha256>
#
# The release workflow runs this after publishing a GitHub Release, then
# commits the result. The formula installs the prebuilt universal macOS
# binary (Apple Silicon and Intel) from that release, so this repository
# doubles as the Homebrew tap.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <sha256>" >&2
  exit 1
fi

version="$1"
sha="$2"
base="https://github.com/HalfdanIsaksen/rusting/releases/download/v${version}"
out="$(dirname "$0")/../Formula/rusting.rb"

mkdir -p "$(dirname "$out")"
cat > "$out" <<EOF
# Generated by scripts/homebrew-formula.sh on each release. Do not edit by hand.
class Rusting < Formula
  desc "Open-source 2D vector animation software"
  homepage "https://github.com/HalfdanIsaksen/rusting"
  url "${base}/rusting-${version}-universal-apple-darwin.tar.gz"
  sha256 "${sha}"
  license "MIT"

  depends_on :macos

  def install
    bin.install "rusting"
  end

  test do
    assert_predicate bin/"rusting", :executable?
  end
end
EOF
echo "wrote $out"
