#!/usr/bin/env bash
# Writes the winget manifests for a released version (ADR-024).
#
# Usage: scripts/winget-manifest.sh <version> <sha256> [out-dir]
#
# <sha256> is the checksum of rusting-<version>-x86_64-pc-windows-msvc.zip.
# The manifests land in <out-dir>/HalfdanIsaksen.Rusting/<version>/
# (default out-dir: dist/winget). The release workflow runs this after
# publishing a GitHub Release and submits the folder to microsoft/winget-pkgs
# with wingetcreate. The package installs the zip's rusting.exe as a portable
# app, so `rusting` works from any new terminal.
set -euo pipefail

if [[ $# -lt 2 || $# -gt 3 ]]; then
  echo "usage: $0 <version> <sha256> [out-dir]" >&2
  exit 1
fi

version="$1"
sha="$(echo "$2" | tr '[:lower:]' '[:upper:]')"
root="${3:-$(dirname "$0")/../dist/winget}"
id="HalfdanIsaksen.Rusting"
schema="1.10.0"
repo="https://github.com/HalfdanIsaksen/rusting"
url="${repo}/releases/download/v${version}/rusting-${version}-x86_64-pc-windows-msvc.zip"
out="${root}/${id}/${version}"
header="# Generated by scripts/winget-manifest.sh on each release. Do not edit by hand."

if [[ ! "$sha" =~ ^[0-9A-F]{64}$ ]]; then
  echo "not a SHA-256: $2" >&2
  exit 1
fi

mkdir -p "$out"

cat > "${out}/${id}.yaml" <<EOF
${header}
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.${schema}.schema.json
PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${schema}
EOF

cat > "${out}/${id}.installer.yaml" <<EOF
${header}
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.${schema}.schema.json
PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: rusting.exe
    PortableCommandAlias: rusting
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Microsoft.VCRedist.2015+.x64
Installers:
  - Architecture: x64
    InstallerUrl: ${url}
    InstallerSha256: ${sha}
ManifestType: installer
ManifestVersion: ${schema}
EOF

cat > "${out}/${id}.locale.en-US.yaml" <<EOF
${header}
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.${schema}.schema.json
PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: HalfdanIsaksen
PublisherUrl: https://github.com/HalfdanIsaksen
PublisherSupportUrl: ${repo}/issues
PackageName: Rusting
PackageUrl: https://rusting-animation.org
License: MIT
LicenseUrl: ${repo}/blob/main/LICENSE
ShortDescription: Free, open-source 2D vector animation software
Description: Draw vector frames and animate them frame by frame on a timeline with layers and onion skin, then export MP4, GIF, PNG or sprite sheets.
Moniker: rusting
Tags:
  - 2d
  - animation
  - drawing
  - gif
  - open-source
  - vector
ReleaseNotesUrl: ${repo}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${schema}
EOF

echo "wrote $out"
